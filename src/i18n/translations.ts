export function translateCategory(name: string, lang: Lang): string {
  return lang === 'ru' ? (CATEGORY_RU[name] ?? name) : name
}

export function translateUnit(unit: string, lang: Lang): string {
  return lang === 'ru' ? (UNIT_RU[unit] ?? unit) : unit
}

export function translateCustomerType(type: string, lang: Lang): string {
  return lang === 'ru' ? (CUSTOMER_TYPE_RU[type] ?? type) : type
}

